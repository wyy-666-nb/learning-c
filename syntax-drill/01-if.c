/*
 * ============================================================
 * 语法点：if / else if / else  —— 分支语句
 * 来源：鹏哥C语言2026
 * 日期：2026-09-11
 * ============================================================
 *
 * 【它解决什么问题】
 * 让程序根据条件走不同的路。
 * 没有 if 的程序只能从上往下一条道执行到底。
 *
 * 【语法格式】
 *   if (条件1)      { 语句 }
 *   else if (条件2) { 语句 }
 *   else            { 语句 }
 *
 * 【关键注意点】
 *   1. 条件必须写在括号里
 *   2. 判断相等用 ==（两个等号）。= 是赋值！
 *   3. else 匹配的是「离它最近的、还没有匹配过的 if」——这就是悬空 else 问题
 *   4. 建议即使只有一行语句也加 { }，否则以后加代码时容易出错
 *   5. 多个条件从上往下依次判断，一旦命中就不再往下看 —— 所以顺序很关键
 *
 * 【和 switch 的区别】
 *   if   适合范围判断，比如 score >= 90
 *   switch 适合等值判断，比如 case 1:
 *
 */

#include <stdio.h>

int main(void)
{
    /* ========== 第 1 部分：最小示例 ========== */

    int score = 85;

    if (score >= 90)
    {
        printf("优秀\n");
    }
    else if (score >= 60)
    {
        printf("及格\n");
    }
    else
    {
        printf("不及格\n");
    }

    /* ========== 第 2 部分：换成我自己的场景 ========== */
    /* 场景换成了「判断闰年」，和分数完全无关 */
    /* 顺便试试这几个值：2024（闰年）2023（平年）1900（平年！）2000（闰年！） */

    int year = 1900;

    if (year % 4 == 0)
    {
        if (year % 100 != 0)
        {
            printf("%d 年是闰年\n", year);
        }
        else if (year % 400 == 0)
        {
            printf("%d 年是闰年\n", year);
        }
        else
        {
            printf("%d 年不是闰年\n", year);
        }
    }
    else
    {
        printf("%d 年不是闰年\n", year);
    }

    /* ========== 第 3 部分：踩坑记录 ========== */

    /* 坑 1：把 == 写成 =
     *
     *     if (score = 90)     // 这是把 90 赋值给 score！
     *                          // 条件变成 score 的值 90，恒为真
     *     编译器可能只给个 warning 就放过去了，程序照跑，但结果全错。
     *     这是 C 语言最经典的 bug 之一。
     */

    /* 坑 2：悬空 else
     *
     *     if (a)
     *         if (b) printf("x\n");
     *     else printf("y\n");     // 这个 else 其实属于 if (b)，不是 if (a)！
     *                             // 缩进骗了你的眼睛，编译器只看就近匹配。
     *     解决办法：不管几行都加大括号。
     */

    /* 坑 3：条件顺序
     *
     *     if (score >= 60)      printf("及格\n");
     *     else if (score >= 90) printf("优秀\n");    // 永远走不到这里！
     *
     *     因为 95 分也会先命中 >= 60。
     *     范围判断必须排好顺序：要么从高档往低档写，要么从低档往高档写，别乱。
     */

    return 0;
}
