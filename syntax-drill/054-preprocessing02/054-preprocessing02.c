#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#define __DEBUG__

int main()
{
    int i = 0;
    int arr[10] = { 0 };
    for (i = 0;i < 10;i++)
    {
        arr[i] = i;
#ifdef __DEBUG__
        printf("%d\n", arr[i]);
#endif
    }
    return 0;
}
